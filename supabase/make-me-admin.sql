/* ══════════════════════════════════════════════════════════════
   통계를 볼 사람을 정합니다 (= 사장님 한 명)

   apply-now.sql 을 먼저 올린 뒤에 하세요.
   그 전까지는 app.admins 표가 없습니다.

   ★ 이걸 하기 전에는 아무도 통계를 못 봅니다. 사장님도요.
     잠긴 쪽이 기본값입니다.
   ══════════════════════════════════════════════════════════════ */


/* ───────── 1단계 — 누가 있는지 봅니다 ─────────

   Supabase → SQL Editor → New query 에 아래 select 만 붙여넣고 Run.
   (한 번에 하나씩 하세요. 결과 표가 보여야 합니다.) */

select u.id              as "이 값을 복사하세요",
       u.email           as "이메일",
       u.created_at      as "가입한 때",
       (a.user_id is not null) as "지금 관리자인가"
  from auth.users u
  left join app.admins a on a.user_id = u.id
 order by u.created_at;


/* ───────── 2단계 — 사장님을 넣습니다 ─────────

   위 결과에서 사장님 줄의 "이 값을 복사하세요" 칸을 복사해서
   아래 ⬛ 자리에 넣고, 이 insert 만 따로 Run 하세요.

   따옴표는 그대로 두고 안쪽만 바꾸시면 됩니다.
   예) '3f2a9c10-7b4e-4d81-9a66-2e5c8d0f1b73'

insert into app.admins (user_id, note)
values ('⬛⬛ 여기에 붙여넣기 ⬛⬛', '사장님')
on conflict (user_id) do nothing;

*/


/* ───────── 3단계 — 제대로 들어갔는지 확인 ─────────

   1단계 select 를 다시 Run 해서, "지금 관리자인가" 가
   사장님 줄만 true 인지 보세요.

   줄이 하나 더 true 면 그 사람도 서비스 전체 숫자를 봅니다.
   빼는 법:

delete from app.admins where user_id = '뺄-사람-uuid';

   전부 비우고 다시 시작하려면:

delete from app.admins;

*/


